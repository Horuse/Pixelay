package dev.horuse.pixelay.content;

import dev.horuse.pixelay.Pixelay;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Stream;
import org.bukkit.plugin.java.JavaPlugin;

/**
 * Glyph widths computed from the resource packs dropped into {@code plugins/Pixelay/resourcepacks/}
 * (folders or zips). The result is written to {@code font-widths.generated.yml} on every enable and
 * {@code /pixelay reload}; that file is overwritten each time, manual values belong in
 * {@code font-widths.yml}.
 */
final class PackFontWidths {

    static final String FOLDER = "resourcepacks";
    static final String GENERATED = "font-widths.generated.yml";

    private PackFontWidths() {}

    /** @return advances by code point (empty when there are no packs or scanning failed) */
    static Map<Integer, PackFontScanner.Glyph> generate(JavaPlugin plugin) {
        Path data = plugin.getDataFolder().toPath();
        Path folder = data.resolve(FOLDER);
        Map<Integer, PackFontScanner.Glyph> result = new HashMap<>();
        try {
            Files.createDirectories(folder);
            List<Path> packs = orderedPacks(folder, Pixelay.settings().resourcePackOrder());
            Map<Integer, PackFontScanner.Glyph> glyphs = PackFontScanner.scan(packs, message ->
                plugin.getLogger().warning("resourcepacks: " + message)
            );
            result.putAll(glyphs);
            Files.writeString(data.resolve(GENERATED), render(packs, glyphs), StandardCharsets.UTF_8);
            if (!packs.isEmpty()) {
                plugin
                    .getLogger()
                    .info("Measured " + glyphs.size() + " glyphs from " + packs.size() + " resource pack(s)");
            }
        } catch (IOException | RuntimeException e) {
            plugin.getLogger().warning("Could not measure resource packs: " + e.getMessage());
        }
        return result;
    }

    /** Packs named in {@code order} first (highest priority first), the rest alphabetically after them. */
    private static List<Path> orderedPacks(Path folder, List<String> order) throws IOException {
        List<Path> found;
        try (Stream<Path> files = Files.list(folder)) {
            found = files
                .filter(path -> Files.isDirectory(path) || path.toString().toLowerCase(Locale.ROOT).endsWith(".zip"))
                .sorted(Comparator.comparing(path -> path.getFileName().toString().toLowerCase(Locale.ROOT)))
                .toList();
        }
        List<Path> ordered = new ArrayList<>();
        for (String name : order) {
            found
                .stream()
                .filter(path -> path.getFileName().toString().equals(name))
                .findFirst()
                .ifPresent(ordered::add);
        }
        found
            .stream()
            .filter(path -> !ordered.contains(path))
            .forEach(ordered::add);
        return ordered;
    }

    private static String render(List<Path> packs, Map<Integer, PackFontScanner.Glyph> glyphs) {
        StringBuilder out = new StringBuilder();
        out.append("# GENERATED by Pixelay from plugins/Pixelay/").append(FOLDER).append("/ — do not edit:\n");
        out.append("# this file is rewritten on every start and /pixelay reload.\n");
        out.append("# Put manual widths into font-widths.yml (they always win over these).\n");
        out.append("# advance: the client's width of the glyph, ink + 1 px spacing (font px);\n");
        out.append("# ascent, height: copied from the glyph's bitmap provider in font/default.json.\n");
        out.append("# Packs (highest priority first): ");
        out.append(
            packs.isEmpty()
                ? "none"
                : String.join(
                      ", ",
                      packs
                          .stream()
                          .map(p -> p.getFileName().toString())
                          .toList()
                  )
        );
        out.append("\nglyphs:");
        if (glyphs.isEmpty()) {
            out.append(" {}\n");
            return out.toString();
        }
        out.append('\n');
        glyphs
            .entrySet()
            .stream()
            .sorted(Map.Entry.comparingByKey())
            .forEach(entry -> {
                PackFontScanner.Glyph glyph = entry.getValue();
                String key = entry.getKey() > 0xFFFF ? "  \"\\U%08X\": " : "  \"\\u%04X\": ";
                out.append(String.format(Locale.ROOT, key, entry.getKey()));
                // Bitmap glyphs always get the full form: ascent and height as in the font provider.
                out.append(
                    glyph.height() > 0
                        ? "{ advance: " +
                              glyph.advance() +
                              ", ascent: " +
                              glyph.ascent() +
                              ", height: " +
                              glyph.height() +
                              " }"
                        : String.valueOf(glyph.advance())
                );
                out.append("  # ").append(glyph.pack()).append(": ").append(glyph.source()).append('\n');
            });
        return out.toString();
    }
}
